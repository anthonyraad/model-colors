import { describe, expect, it } from 'vitest'
import { createMotionState, createTapePicture, dropReverse, motionKind, motionLabel, motionSnap, reverseLengthBeats, stepTapePicture, tapeSpeed, tapeWindBeats, toggleMotion, writeMotion } from './motion'

describe('reverse and tape stop', () => {
  it('maps the minus and equal keys', () => {
    expect(motionKind('Minus', '-', false)).toBe('reverse')
    expect(motionKind('Equal', '=', false)).toBe('tape')
    expect(motionKind('NumpadSubtract', '-', false)).toBe('reverse')
    expect(motionKind('Equal', '+', true)).toBeNull()
    expect(motionKind('Minus', '_', true)).toBeNull()
    expect(motionKind('KeyA', 'a', false)).toBeNull()
  })

  it('toggles one motion and clears the other', () => {
    const state = createMotionState()
    toggleMotion(state, 'reverse')
    expect(state.reverse).toBe(true)
    expect(motionLabel(state)).toBe('Reverse')
    toggleMotion(state, 'tape')
    expect(state.tape).toBe(true)
    expect(state.reverse).toBe(false)
    expect(motionLabel(state)).toBe('Tape stop')
    toggleMotion(state, 'tape')
    expect(state.tape).toBe(false)
    expect(motionLabel(state)).toBe('')
  })

  it('winds the tape from full speed down to a stop and back', () => {
    expect(tapeSpeed(0, 1, 0)).toBeCloseTo(1)
    expect(tapeSpeed(1, 1, 0)).toBeCloseTo(0)
    expect(tapeSpeed(0.5, 1, 0)).toBeGreaterThan(0.5)
    expect(tapeSpeed(0, 0, 1)).toBeCloseTo(0)
    expect(tapeSpeed(1, 0, 1)).toBeCloseTo(1)
    expect(tapeSpeed(0.5, 0, 1)).toBeGreaterThan(0.5)
    expect(reverseLengthBeats(1)).toBe(4)
    expect(reverseLengthBeats(2)).toBe(8)
    expect(reverseLengthBeats(4)).toBe(16)
    expect(reverseLengthBeats(8)).toBe(32)
    expect(reverseLengthBeats(3)).toBe(16)
    expect(tapeWindBeats('slow')).toBe(4)
    expect(tapeWindBeats('medium')).toBe(2)
    expect(tapeWindBeats('fast')).toBe(1)
    expect(tapeWindBeats('other')).toBe(2)
    const off = createMotionState()
    const reverse = createMotionState()
    reverse.reverse = true
    const tape = createMotionState()
    tape.tape = true
    expect(motionSnap(reverse, off, true, false)).toBe('reverse')
    expect(motionSnap(reverse, off, false, true)).toBeNull()
    expect(motionSnap(tape, off, false, true)).toBe('tape')
    expect(motionSnap(tape, off, true, false)).toBeNull()
    expect(motionSnap(off, reverse, true, true)).toBe('reverse')
    expect(motionSnap(off, tape, true, true)).toBe('tape')
    expect(motionSnap(tape, reverse, true, true)).toBe('tape')
    expect(motionSnap(reverse, tape, true, false)).toBe('reverse')
    const playing = createMotionState()
    playing.reverse = true
    const asked = createMotionState()
    asked.reverse = true
    expect(dropReverse(asked, playing)).toBe(true)
    expect(asked.reverse).toBe(false)
    expect(playing.reverse).toBe(false)
    expect(motionSnap(asked, playing, true, true)).toBeNull()
    asked.tape = true
    expect(motionSnap(asked, playing, true, true)).toBe('tape')
    expect(playing.reverse).toBe(false)
    const quiet = createMotionState()
    expect(dropReverse(quiet, createMotionState())).toBe(false)
    const state = createMotionState()
    writeMotion(state, 'tape')
    expect(state.tape).toBe(true)
    writeMotion(state, null)
    expect(state.tape).toBe(false)
    expect(state.reverse).toBe(false)
  })

  it('stops the picture clock with the tape and brings it back', () => {
    const picture = createTapePicture(1_000)
    expect(stepTapePicture(picture, false, 2, 120, 0.016, 1_016)).toBe(1)
    expect(picture.now).toBe(1_016)
    stepTapePicture(picture, true, 2, 120, 0, 2_000)
    expect(picture.phase).toBe('stopping')
    expect(picture.rate).toBeCloseTo(1)
    stepTapePicture(picture, true, 2, 120, 0.5, 2_500)
    expect(picture.rate).toBeCloseTo(0.5)
    expect(picture.now).toBeGreaterThan(1_000)
    expect(picture.now).toBeLessThan(2_500)
    const crawling = createTapePicture(1_000)
    stepTapePicture(crawling, true, 2, 120, 0, 1_000)
    const earlyAt = crawling.now
    stepTapePicture(crawling, true, 2, 120, 0.1, 1_100)
    const earlyMove = crawling.now - earlyAt
    stepTapePicture(crawling, true, 2, 120, 0.7, 1_800)
    const lateAt = crawling.now
    stepTapePicture(crawling, true, 2, 120, 0.1, 1_900)
    expect(crawling.phase).toBe('stopping')
    expect(crawling.now - lateAt).toBeLessThan(earlyMove * 0.15)
    stepTapePicture(picture, true, 2, 120, 0.6, 3_100)
    expect(picture.phase).toBe('stopped')
    expect(picture.rate).toBe(0)
    const frozen = picture.now
    stepTapePicture(picture, true, 2, 120, 0.2, 3_300)
    expect(picture.now).toBe(frozen)
    stepTapePicture(picture, false, 2, 120, 0, 4_000)
    expect(picture.phase).toBe('returning')
    stepTapePicture(picture, false, 2, 120, 1, 5_000)
    expect(picture.phase).toBe('idle')
    expect(picture.rate).toBe(1)
    expect(picture.now).toBe(5_000)
  })
})
